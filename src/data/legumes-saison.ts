export function getLegumesDuMois(mois?: number): string[] {
  const month = mois ?? new Date().getMonth() + 1;

  if (!Number.isInteger(month) || month < 1 || month > 12) {
    return [];
  }

  return [...(LEGUMES_PAR_MOIS[month] ?? [])];
}
